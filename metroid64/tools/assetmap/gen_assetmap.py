#!/usr/bin/env python3
"""Generates metroid64/src/game/data/AssetMap.inc: where the game's data is in the ROM.

Reads the community disassembly (github.com/nmikstas/metroid-disassembly, not included in this
repository) annotated with addresses, and lists every run of data (.byte/.word) as a block named after
the label it starts at. Only addresses and names are written: no data. The extractor copies the blocks
out of the player's ROM.

usage: gen_assetmap.py <disassembly dir with BankNN.addr.asm, BankNN.labels, Bank06.asm> > AssetMap.inc
"""
import re
import sys

# Bytes the original reads as data although they are instructions (tables read past their end).
EXTRA = {
    0: [(0x909F, 1)],               # title: read past a table into ClearAll
    3: [(0x9F00, 2), (0xA140, 1)],  # Tourian: Mother Brain's death palettes run into code
    5: [(0x98D5, 2)],               # Ridley's hideout
    7: [(0xF01C, 1)],               # FillRoomRAM's first byte
}

line_re = re.compile(r'^([0-9A-F]{4})\s+(?:\w+:\s*)?(?:[\*\+\-]+\s*)?(.*)$')


def bank_data(d, bank):
    base = 0xC000 if bank == 7 else 0x8000
    mask = bytearray(0x4000)
    names = {}
    if bank == 6:
        pending = None
        for line in open(f'{d}/Bank06.asm'):
            m = re.match(r'^(\w+):\s*$', line)
            if m:
                pending = m.group(1)
                continue
            m = re.match(r'^L([0-9A-F]{4}):\s*\.byte\s*(.*)', line)
            if m:
                a = int(m.group(1), 16)
                n = len(m.group(2).split(';')[0].split(','))
                for x in range(a, a + n):
                    mask[x - base] = 1
                if pending:
                    names[a] = pending
                    pending = None
        return mask, names
    entries = []
    for line in open(f'{d}/Bank{bank:02d}.addr.asm'):
        m = line_re.match(line)
        if not m:
            continue
        body = m.group(2).split(';')[0].strip().lower()
        if body:
            entries.append((int(m.group(1), 16), body.startswith('.byte') or body.startswith('.word')))
    entries.sort()
    for i, (a, isdata) in enumerate(entries):
        end = entries[i + 1][0] if i + 1 < len(entries) else base + 0x4000
        if isdata:
            for x in range(a, min(end, base + 0x4000)):
                mask[x - base] = 1
    for line in open(f'{d}/Bank{bank:02d}.labels'):
        p = line.split()
        if len(p) >= 2:
            names[int(p[0], 16)] = p[1]
    return mask, names


def main():
    d = sys.argv[1]
    print('// Generated by tools/assetmap/gen_assetmap.py from the Metroid disassembly: where the game\'s')
    print('// data is in the ROM (bank, address, length, name). Addresses and names only, no data.')
    for bank in range(8):
        base = 0xC000 if bank == 7 else 0x8000
        mask, names = bank_data(d, bank)
        for a, n in EXTRA.get(bank, []):
            for x in range(a, a + n):
                mask[x - base] = 1
        last = 'Bank%d' % bank
        lastAddr = base
        i = 0
        while i < 0x4000:
            if not mask[i]:
                a = base + i
                if a in names:
                    last, lastAddr = names[a], a
                i += 1
                continue
            start = i
            j = i + 1
            while j < 0x4000 and mask[j] and (base + j) not in names:
                j += 1
            a = base + start
            if a in names:
                last, lastAddr = names[a], a
                name = last
            else:
                name = '%s_%X' % (last, a - lastAddr)
            print('{ %d, 0x%04X, %d, "%s" },' % (bank, a, j - start, name))
            i = j


main()
